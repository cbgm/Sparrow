class EmbeddingGemmaParityDeviceTest {
    @Test
    fun matchesTrainingPipelineReferenceEmbeddings() = runBlocking {
        val arguments = InstrumentationRegistry.getArguments()
        if (!arguments.getString(ARGUMENT_RUN_PARITY).toBoolean()) return@runBlocking

        val context = ApplicationProvider.getApplicationContext<Context>()
        val modelFiles = AndroidLocalEmbeddingModelFiles(context)
        ensurePinnedModel(modelFiles)

        val modelManager = AndroidLocalEmbeddingModelManager(context, modelFiles)
        val embedder = MediaPipeLocalTextEmbedder(context, modelManager)

        try {
            REFERENCES.forEach { reference ->
                val actual =
                    embedder
                        .embed(reference.text, EmbeddingInputType.SEMANTIC_SIMILARITY)
                        .normalizedPrefix(LocalEmbeddingModel.OUTPUT_DIMENSIONS)

                assertEquals(
                    expected = reference.embedding.size,
                    actual = actual.size,
                    message = "Embedding dimension mismatch for ${reference.id}"
                )

                val cosine = cosineSimilarity(reference.embedding, actual)
                val maxAbsoluteDelta =
                    reference.embedding.indices.maxOf { index ->
                        abs(reference.embedding[index] - actual[index])
                    }

                assertTrue(
                    cosine >= MINIMUM_COSINE_SIMILARITY,
                    "Embedding cosine parity failed for ${reference.id}: cosine=$cosine"
                )
                assertTrue(
                    maxAbsoluteDelta <= MAXIMUM_ABSOLUTE_DELTA,
                    "Embedding value parity failed for ${reference.id}: maxAbsoluteDelta=$maxAbsoluteDelta"
                )
            }
        } finally {
            embedder.close()
        }
    }

    private suspend fun ensurePinnedModel(modelFiles: AndroidLocalEmbeddingModelFiles) {
        if (modelFiles.isModelReady()) return

        modelFiles.ensureDirectory()
        val connection =
            (
                withContext(Dispatchers.IO) {
                    URL(LocalEmbeddingModel.MODEL_URL).openConnection()
                } as HttpURLConnection
            ).apply {
                connectTimeout = DOWNLOAD_CONNECT_TIMEOUT_MILLISECONDS
                readTimeout = DOWNLOAD_READ_TIMEOUT_MILLISECONDS
                instanceFollowRedirects = true
            }

        try {
            withContext(Dispatchers.IO) {
                connection.connect()
            }
            check(connection.responseCode in 200..299) {
                "EmbeddingGemma download failed with HTTP ${connection.responseCode}"
            }
            connection.inputStream.buffered().use { input ->
                modelFiles.partialFile.outputStream().buffered().use { output ->
                    input.copyTo(output)
                }
            }
        } finally {
            connection.disconnect()
        }

        val sha256 = modelFiles.sha256(modelFiles.partialFile)
        assertEquals(
            expected = LocalEmbeddingModel.MODEL_SHA256,
            actual = sha256,
            message = "Downloaded EmbeddingGemma SHA-256 mismatch"
        )
        modelFiles.promoteVerifiedDownload(sha256)
    }

    private data class Reference(
        val id: String,
        val text: String,
        val embedding: FloatArray
    ) {
        override fun equals(other: Any?): Boolean {
            if (this === other) return true
            if (javaClass != other?.javaClass) return false

            other as Reference

            if (id != other.id) return false
            if (text != other.text) return false
            if (!embedding.contentEquals(other.embedding)) return false

            return true
        }

        override fun hashCode(): Int {
            var result = id.hashCode()
            result = 31 * result + text.hashCode()
            result = 31 * result + embedding.contentHashCode()
            return result
        }
    }

