package com.cbgm.sparrow.buildlogic.workflow.render

import com.cbgm.sparrow.buildlogic.workflow.parse.WorkflowDescription
import com.cbgm.sparrow.buildlogic.workflow.parse.WorkflowSourceParser

/** One orchestration module of the catalog and its workflows. */
internal data class WorkflowModule(
    val name: String,
    val workflows: List<WorkflowDescription>,
)

/** Renders `index.md` and one page per module, keyed by file name. */
internal object WorkflowCatalogRenderer {

    /** Modules in layering order; the catalog shows them in this order. */
    val MODULES = listOf("delivery", "message", "groupstate", "membership", "lifecycle", "incoming")

    private val TITLES = mapOf(
        "delivery" to "Delivery workflows",
        "message" to "Message workflows",
        "groupstate" to "Group state workflows",
        "membership" to "Membership workflows",
        "lifecycle" to "Direct chat lifecycle workflows",
        "incoming" to "Incoming packet workflows",
    )

    private val INTROS = mapOf(
        "delivery" to "Outbox and transport progress: which state a sent message or recipient is in.",
        "message" to "Writing, changing, reading and retrying Direct and Group messages, polls and forwarding.",
        "groupstate" to "State an admin sets for the whole group and broadcasts to every member: title, " +
            "description, avatar, pin and the expense board.",
        "membership" to "Creating and administrating groups, joining a group and group verification.",
        "lifecycle" to "How a direct chat is opened, gets authorized, loses its authorization and recovers it.",
        "incoming" to "Routing every decrypted packet to the one workflow that applies it.",
    )

    private const val GENERATED_BY = "Generated by `./gradlew workflowCatalog`"

    fun render(modules: List<WorkflowModule>): Map<String, String> =
        modules.associate { module -> "${module.name}.md" to modulePage(module) } +
            ("index.md" to indexPage(modules))

    private fun title(module: String) = TITLES[module] ?: "${module.replaceFirstChar(Char::uppercase)} workflows"

    private fun modulePage(module: WorkflowModule): String {
        val out = mutableListOf(
            "# ${title(module.name)}",
            "",
            "_${GENERATED_BY} from `:feature:conversationorchestration:${module.name}`. Do not edit by hand._",
            "",
            INTROS[module.name].orEmpty(),
            "",
            "Diagram legend: boxes are `Step`s, arrow labels are the `Outcome` a step reported, " +
                "`[*]` is the start or a successful completion, `Rejected` ends the workflow with a " +
                "`ConversationFailure`.",
            "",
            "| Workflow | Started by | Command | Lock |",
            "|---|---|---|---|",
        )
        module.workflows.forEach { workflow ->
            val starter = if (workflow.isPublic) "Chats (`ConversationOrchestrator`)" else "orchestration (`engine.run`)"
            out += "| [`${workflow.className}`](#${workflow.className.lowercase()}) | $starter | " +
                "`${workflow.command}` | ${code(workflow.lockKey) ?: "—"} |"
        }
        var currentFolder: String? = null
        module.workflows.forEach { workflow ->
            if (workflow.folder != currentFolder) {
                currentFolder = workflow.folder
                out += listOf("", "## `${workflow.folder.ifEmpty { module.name }}`")
            }
            val kind = if (workflow.isPublic) {
                "public — Chats submits"
            } else {
                "internal — started by an observer, dispatcher or another workflow"
            }
            out += listOf(
                "",
                "### ${workflow.className}",
                "",
                "- **Kind:** $kind `${workflow.command}`",
                "- **Source:** `${workflow.sourcePath}`",
                "- **Lock:** ${code(workflow.lockKey) ?: "none"}",
                "- **Uses:** ${workflow.dependencies.joinToString(", ") { "`$it`" }.ifEmpty { "—" }}",
                "",
            )
            if (workflow.kdoc.isNotEmpty()) {
                out += listOf("```text", workflow.kdoc, "```", "")
            }
            out += diagram(workflow)
        }
        return out.joinToString("\n") + "\n"
    }

    private fun diagram(workflow: WorkflowDescription): String {
        val lines = mutableListOf("```mermaid", "stateDiagram-v2")
        workflow.firstSteps.forEach { step -> lines += "    [*] --> $step" }
        data class Edge(val step: String, val target: String, val outcome: String)
        val edges = workflow.steps.flatMap { step ->
            workflow.stepOutcomes[step].orEmpty().flatMap { outcome ->
                workflow.transitions[step to outcome].orEmpty().map { target -> Edge(step, target, outcome) }
            }
        }.distinct().sortedWith(
            compareBy<Edge>({ workflow.steps.indexOf(it.step) }, { it.outcome }, { it.target }),
        )
        edges.forEach { edge -> lines += "    ${edge.step} --> ${edge.target} : ${edge.outcome}" }
        if (edges.any { it.target == WorkflowSourceParser.REJECTED }) {
            lines += "    Rejected --> [*]"
            lines += "    classDef reject fill:#f8d7da,stroke:#b02a37,color:#58151c"
            lines += "    class Rejected reject"
        }
        lines += "```"
        return lines.joinToString("\n")
    }

    private fun indexPage(modules: List<WorkflowModule>): String {
        val out = mutableListOf(
            "# Workflow catalog",
            "",
            "_${GENERATED_BY}; `./gradlew qualityCheck` fails when it is out of date. Do not edit by hand._",
            "",
            "Every command has exactly one workflow. Public commands (`ConversationCommand` in " +
                "`:feature:conversationorchestration:api`) are submitted by Chats through `ConversationOrchestrator`; " +
                "internal commands (`*Command : WorkflowCommand`) are submitted inside orchestration with " +
                "`engine.run(command)`. See [Conversation orchestration](../conversation-orchestration.md) for the " +
                "engine itself.",
            "",
            "| Module | Workflows | Public | Internal |",
            "|---|---|---|---|",
        )
        modules.forEach { module ->
            val public = module.workflows.count { it.isPublic }
            out += "| [${title(module.name)}](${module.name}.md) | ${module.workflows.size} | $public | " +
                "${module.workflows.size - public} |"
        }
        out += commandTable(modules, "## Public commands (Chats → `ConversationOrchestrator`)") { it.isPublic }
        out += commandTable(modules, "## Internal commands (`engine.run(command)`)") { !it.isPublic }
        val locks = sortedMapOf<String, MutableList<String>>()
        modules.flatMap { it.workflows }.forEach { workflow ->
            val lock = workflow.lockKey ?: return@forEach
            val key = if (lock.startsWith("\"")) lock else lock.substringBefore('(')
            locks.getOrPut(key) { mutableListOf() } += workflow.className
        }
        out += listOf(
            "",
            "## Locks",
            "",
            "Workflows that share a lock key never run at the same time (`WorkflowLocks`). Locks are not " +
                "reentrant: a nested `engine.run(command, acquireLock = false)` is used when the caller already " +
                "holds the same key.",
            "",
            "| Lock key | Workflows |",
            "|---|---|",
        )
        locks.forEach { (key, workflows) ->
            out += "| `$key` | ${workflows.sorted().joinToString(", ") { "`$it`" }} |"
        }
        return out.joinToString("\n") + "\n"
    }

    private fun commandTable(
        modules: List<WorkflowModule>,
        heading: String,
        include: (WorkflowDescription) -> Boolean,
    ): List<String> {
        val rows = modules
            .flatMap { module -> module.workflows.filter(include).map { module.name to it } }
            .sortedWith(compareBy({ it.second.command }, { it.second.className }))
            .map { (module, workflow) ->
                "| `${workflow.command}` | [`${workflow.className}`]($module.md#${workflow.className.lowercase()}) | " +
                    "`$module` | ${code(workflow.lockKey) ?: "—"} |"
            }
        return listOf("", heading, "", "| Command | Workflow | Module | Lock |", "|---|---|---|---|") + rows
    }

    private fun code(value: String?): String? = value?.let { "`$it`" }
}
